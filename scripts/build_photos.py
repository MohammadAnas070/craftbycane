"""
Builds the optimised photo assets from the supplied cane_img.zip folders.

  python -I scripts/build_photos.py <extracted cane_img dir> <rembg cut-out dir>

* Originals are copied untouched to assets-src/cane_img/ (not shipped with the site).
* src/assets/images/photos/<category>/<n>.webp   full photo, max 1200 px  (gallery, detail, cover use)
* src/assets/images/products/<category>/<n>.webp background-removed cut-out (transparent), max 1000 px
  (only for images where removal looks clean; chosen in CUT below)
* src/app/core/data/photos.generated.ts           manifest consumed by the app

Cut-outs are produced by rembg (u2net) with `scripts/cut_backgrounds.py`.
"""
import json
import os
import re
import shutil
import sys

from PIL import Image

SRC, CUTS = sys.argv[1], sys.argv[2]
ROOT = os.path.join(os.path.dirname(__file__), "..")
OUT = os.path.join(ROOT, "src", "assets", "images")
KEEP = os.path.join(ROOT, "assets-src", "cane_img")

SLUG = {
    "cane_handmade": "cane-handmade", "cane_stepler": "cane-stepler", "cane_stick": "cane-stick",
    "cane_wicker": "cane-wicker", "rope_work": "rope-work", "lamp": "lamp", "jula_furniture": "zula-furniture",
}

# images whose background removal looks clean enough to use (per source folder)
CUT = json.loads(open(os.path.join(os.path.dirname(__file__), "cut_selection.json")).read())
# images that are too poor to show at all
SKIP = json.loads(open(os.path.join(os.path.dirname(__file__), "skip_selection.json")).read())


def num(name):
    return int(re.findall(r"\d+", name)[0])


manifest = {}
for folder in sorted(os.listdir(SRC)):
    slug = SLUG.get(folder)
    if not slug:
        continue
    shutil.copytree(os.path.join(SRC, folder), os.path.join(KEEP, folder), dirs_exist_ok=True)
    os.makedirs(os.path.join(OUT, "photos", slug), exist_ok=True)
    os.makedirs(os.path.join(OUT, "products", slug), exist_ok=True)
    entries = {}
    for f in sorted(os.listdir(os.path.join(SRC, folder)), key=num):
        if not f.endswith(".jpg"):
            continue
        n = num(f)
        if n in SKIP.get(folder, []):
            continue
        im = Image.open(os.path.join(SRC, folder, f)).convert("RGB")
        im.thumbnail((1200, 1200), Image.LANCZOS)
        im.save(os.path.join(OUT, "photos", slug, f"{n}.webp"), "WEBP", quality=76, method=6)
        e = {"photo": {"src": f"assets/images/photos/{slug}/{n}.webp", "w": im.width, "h": im.height}}
        if n in CUT.get(folder, []):
            cut = Image.open(os.path.join(CUTS, folder, f"img{n}.png")).convert("RGBA")
            cut.thumbnail((1000, 1000), Image.LANCZOS)
            cut.save(os.path.join(OUT, "products", slug, f"{n}.webp"), "WEBP", quality=88, method=6, exact=True)
            e["cut"] = {"src": f"assets/images/products/{slug}/{n}.webp", "w": cut.width, "h": cut.height}
        entries[n] = e
    manifest[slug] = entries
    print(slug, len(entries), "photos,", sum('cut' in v for v in entries.values()), "cut-outs")

ts = "// Generated by scripts/build_photos.py. Do not edit by hand.\n"
ts += "export interface PhotoFile { src: string; w: number; h: number }\n"
ts += "export interface Photo { photo: PhotoFile; cut?: PhotoFile }\n"
ts += "export const PHOTOS: Record<string, Record<number, Photo>> = " + json.dumps(manifest, indent=1) + ";\n"
open(os.path.join(ROOT, "src", "app", "core", "data", "photos.generated.ts"), "w", encoding="utf-8").write(ts)
